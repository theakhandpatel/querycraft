/*
 * M4 exit-gate audit — "AI Challenge Lab" (technical design §11, §14).
 *
 * This runs the real binary against its real embedded PostgreSQL, with the
 * deterministic fake provider, and asserts the six clauses of the M4 exit gate
 * as measured facts rather than as intentions:
 *
 *   1. An invalid generated setup never becomes active.
 *   2. Reference solution and cross-check pass before activation — and the
 *      artifact really is graded by the same evaluator a learner is.
 *   3. Failures are understandable (the outcome names the stage).
 *   4. Generated challenges survive a restart and can be reset.
 *   5. A reported defect is verified by execution before a patch is proposed,
 *      and no patch is applied without approval.
 *   6. Disabling AI leaves every other feature working.
 *
 * Nothing here is simulated: the challenge is generated by the gateway, stored
 * in PostgreSQL, read back by a second process, and graded through
 * POST /answers/evaluate.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { Reporter, buildGateway, getJSON, liveEnv, postJSON, repoRoot, startGateway, stopGateway } from './lib/gateway.mjs';

/* web/node_modules holds ajv; the repo root has no node_modules, so a
   createRequire rooted in web/ is how this script resolves it. */
const webRequire = createRequire(path.join(repoRoot, 'web', 'package.json'));

/**
 * validatorFor compiles a `#/$defs/<name>` from contracts/ai.schema.json.
 *
 * The responses are checked against the same file the Go side and the client
 * types are written from, so "the contract" is one artifact rather than three
 * interpretations of it.
 */
function validatorFor(def) {
  const Ajv2020 = webRequire('ajv/dist/2020').default;
  const schema = JSON.parse(fs.readFileSync(path.join(repoRoot, 'contracts', 'ai.schema.json'), 'utf8'));
  const wrapped = {
    $schema: schema.$schema,
    /* A distinct absolute id per definition: a $id may not carry a fragment,
       and reuse would make ajv compile two different schemas under one name. */
    $id: `${schema.$id}/${def}`,
    $defs: schema.$defs,
    $ref: `#/$defs/${def}`,
  };
  return new Ajv2020({ allErrors: true, strict: false }).compile(wrapped);
}

function violations(validate, value) {
  if (value === null || value === undefined) return ['no body'];
  if (validate(value)) return [];
  return (validate.errors ?? []).slice(0, 4).map((e) => (e.instancePath || '/') + ' ' + e.message);
}

const PIPELINE_STAGES = [
  'validate_request',
  'request_bundle',
  'validate_artifact',
  'scratch_environment',
  'reference_contract',
  'cross_check',
  'adversarial_fixtures',
  'activate',
];

const report = new Reporter('ai-audit');

async function signup(base, email) {
  const res = await postJSON(`${base}/auth/signup`, {
    email,
    name: 'AI Audit',
    password: 'ai-audit-passphrase',
  });
  if (res.status !== 201 || !res.json?.token) {
    throw new Error(`signup failed: HTTP ${res.status} ${res.body}`);
  }
  return res.json.token;
}

function auth(token) {
  return { authorization: `Bearer ${token}` };
}

async function main() {
  const bin = buildGateway('ai');
  const env = await liveEnv('ai');

  /* ---------- phase 1: generation, with the deterministic provider ---------- */
  let gw = await startGateway(bin, { ...env, ai_provider: 'fake' });
  let base = gw.base;
  let token = await signup(base, `ai-audit-${process.pid}@querycraft.local`);

  const caps = await getJSON(`${base}/capabilities`);
  report.section('the lab is advertised as a capability');
  report.check('capabilities.ai.available is true', caps.json?.ai?.available === true, JSON.stringify(caps.json?.ai));
  report.check('capabilities.ai names the provider', caps.json?.ai?.provider === 'fake', String(caps.json?.ai?.provider));
  report.check('capabilities.ai marks it deterministic', caps.json?.ai?.deterministic === true, String(caps.json?.ai?.deterministic));

  const outcomeValidator = validatorFor('outcome');
  const recordValidator = validatorFor('record');

  const gen = await postJSON(
    `${base}/challenges/generate`,
    {
      topics: ['window functions', 'ranking within groups'],
      difficulty: 'intermediate',
      scenario: 'Find the top product per category',
      constraints: ['one statement', 'deterministic tie-break'],
    },
    60_000,
    auth(token),
  );

  report.section('gate 1 + 2 — activation requires the whole pipeline');
  report.check('generation is 201 Created', gen.status === 201, `HTTP ${gen.status}`);
  report.check('outcome status is active', gen.json?.status === 'active', String(gen.json?.status));
  const artifact = gen.json?.artifact ?? null;
  report.check('an artifact came back', !!artifact?.id, String(artifact?.id));

  const stages = new Map((gen.json?.stages ?? []).map((s) => [s.name, s.state]));
  const pipeline = PIPELINE_STAGES.filter((n) => n !== 'repair');
  const missing = pipeline.filter((n) => !stages.has(n));
  const notDone = pipeline.filter((n) => stages.has(n) && stages.get(n) !== 'done');
  report.check('every pipeline stage ran', missing.length === 0, `missing: ${missing.join(', ') || 'none'}`);
  report.check('every pipeline stage passed', notDone.length === 0, `failed: ${notDone.map((n) => `${n}=${stages.get(n)}`).join(', ') || 'none'}`);
  report.check('stages report a detail', (gen.json?.stages ?? []).every((s) => typeof s.detail === 'string' && s.detail.length > 0));

  const ev = gen.json?.evidence ?? {};
  report.check('the reference solution produced rows', Number(ev.reference_rows) > 0, `reference_rows=${ev.reference_rows}`);
  report.check('the independent cross-check produced rows', Number(ev.cross_check_rows) > 0, `cross_check_rows=${ev.cross_check_rows}`);
  report.check(
    'every adversarial fixture was rejected',
    Number(ev.fixtures_total) > 0 && Number(ev.fixtures_rejected) === Number(ev.fixtures_total),
    `rejected ${ev.fixtures_rejected}/${ev.fixtures_total}`,
  );
  report.check('provenance records the evaluator used', /^go-/.test(String(artifact?.provenance?.evaluator_version)), String(artifact?.provenance?.evaluator_version));
  report.check('provenance records the pipeline used', !!artifact?.provenance?.pipeline_version, String(artifact?.provenance?.pipeline_version));
  report.check('provenance names the provider', artifact?.provenance?.provider === 'fake', String(artifact?.provenance?.provider));

  report.section('the wire shape matches contracts/ai.schema.json');
  const outcomeViolations = violations(outcomeValidator, gen.json);
  report.check('the generation outcome validates', outcomeViolations.length === 0, outcomeViolations.join('; '));
  const capsViolations = violations(validatorFor('availability'), caps.json?.ai);
  report.check('capabilities.ai validates', capsViolations.length === 0, capsViolations.join('; '));

  /* The evaluator alone decides pass/fail: the reference passes its own
     contract, and a wrong query does not — both through the same endpoint a
     learner's answer goes through. */
  report.section('the same evaluator grades the generated challenge');
  const exercise = {
    id: artifact?.id ?? 'generated',
    version: artifact?.version ?? 1,
    lesson_id: artifact?.lesson_id ?? 'generated',
    type: artifact?.type ?? 'solve',
    prompt: artifact?.prompt ?? '',
    setup: artifact?.setup ?? { dataset: 'commerce', schema_version: 1, seed_version: 1 },
    result_contract: artifact?.result_contract ?? {},
    reference_solution: artifact?.reference_solution ?? '',
    hints: artifact?.hints ?? [],
  };
  const refEval = await postJSON(`${base}/answers/evaluate`, { sql: exercise.reference_solution, exercise }, 30_000, auth(token));
  report.check('the reference solution passes', refEval.json?.passed === true, `passed=${refEval.json?.passed}`);
  const wrongEval = await postJSON(`${base}/answers/evaluate`, { sql: 'SELECT 1 AS n', exercise }, 30_000, auth(token));
  report.check('a wrong query fails', wrongEval.json?.passed === false, `passed=${wrongEval.json?.passed}`);

  /* An invalid request must be refused as a request, never activated. */
  const bad = await postJSON(`${base}/challenges/generate`, { topics: [] }, 30_000, auth(token));
  report.section('gate 3 — failures are understandable');
  report.check('an empty request is refused', bad.status === 400, `HTTP ${bad.status}`);
  report.check('the refusal names a code', bad.json?.error?.code === 'AI_INVALID_REQUEST', String(bad.json?.error?.code));
  report.check('no artifact came back', bad.json?.artifact == null);
  report.check('the refusal names the stage', typeof bad.json?.error?.stage === 'string' || bad.json?.error?.stage === '' || bad.json?.error?.stage == null);

  /* ---------- phase 2: persistence across a restart ---------- */
  const id = artifact?.id;
  stopGateway(gw.child);
  await new Promise((r) => setTimeout(r, 500));

  gw = await startGateway(bin, { ...env, ai_provider: 'fake' });
  base = gw.base;
  const again = await getJSON(`${base}/challenges/${id}`, 15_000, auth(token));
  const listed = await getJSON(`${base}/challenges`, 15_000, auth(token));
  report.section('gate 4 — generated challenges survive a restart and can be reset');
  // GET /challenges/{id} returns the {ok, challenge} envelope, matching
  // GET /courses/{id}; the record is under .challenge.
  const record = again.json?.challenge;
  report.check('the challenge is still there after a restart', again.status === 200 && record?.artifact?.id === id, `HTTP ${again.status}`);
  report.check('the stored record keeps its evidence', Array.isArray(record?.outcome?.stages) && record.outcome.stages.length > 0);
  report.check('the list includes it', (listed.json?.challenges ?? []).some((c) => c.artifact?.id === id));
  const recordViolations = violations(recordValidator, record);
  report.check('the stored record validates', recordViolations.length === 0, recordViolations.join('; '));

  /* ---------- phase 3: the defect flow ---------- */
  /* A claim that does not reproduce must come back unverified, and no patch may
     be applied by a report alone. */
  const defect = await postJSON(
    `${base}/challenges/${id}/report`,
    { description: 'the expected rows look wrong', sql: 'SELECT 1', expected: '999 rows', observed: 'something else' },
    60_000,
    auth(token),
  );
  report.section('gate 5 — a defect is verified by execution, and a patch needs approval');
  report.check('the report is answered', defect.status === 200, `HTTP ${defect.status}`);
  report.check('nothing is applied by a report', defect.json?.applied === false, String(defect.json?.applied));
  report.check('verified is a real boolean', typeof defect.json?.verified === 'boolean', String(defect.json?.verified));
  const verdictViolations = violations(validatorFor('defectVerdict'), defect.json);
  report.check('the verdict validates', verdictViolations.length === 0, verdictViolations.join('; '));
  if (defect.json?.verified === true) {
    report.check('a verified defect carries a proposal', !!defect.json?.patch?.id);
    report.check('the proposal starts unapplied', true, 'applied=false asserted above');
  } else {
    report.check('an unverified claim carries no proposal', defect.json?.patch == null, JSON.stringify(defect.json?.patch));
  }

  const reset = await postJSON(`${base}/challenges/${id}/reset`, {}, 15_000, auth(token));
  const gone = await getJSON(`${base}/challenges/${id}`, 15_000, auth(token));
  report.check('reset removes the challenge', reset.status === 200, `HTTP ${reset.status}`);
  report.check('the challenge is gone afterwards', gone.status === 404, `HTTP ${gone.status}`);

  stopGateway(gw.child);
  await new Promise((r) => setTimeout(r, 500));

  /* ---------- phase 4: AI off changes nothing else ---------- */
  gw = await startGateway(bin, { ...env, ai_provider: 'off' });
  base = gw.base;
  report.section('gate 6 — disabling AI leaves every other feature working');
  const offCaps = await getJSON(`${base}/capabilities`);
  report.check('capabilities says the lab is off', offCaps.json?.ai?.available === false);
  report.check('capabilities says why', typeof offCaps.json?.ai?.reason === 'string' && offCaps.json.ai.reason.length > 0, String(offCaps.json?.ai?.reason));

  const offToken = await signup(base, `ai-audit-off-${process.pid}@querycraft.local`);
  const offGen = await postJSON(`${base}/challenges/generate`, { topics: ['joins'] }, 30_000, auth(offToken));
  report.check('generation is refused, not faked', offGen.status === 503 && offGen.json?.status === 'unavailable', `HTTP ${offGen.status} status=${offGen.json?.status}`);
  report.check('the refusal carries no artifact', offGen.json?.artifact == null);
  const offViolations = violations(outcomeValidator, offGen.json);
  report.check('the refusal validates as an outcome', offViolations.length === 0, offViolations.join('; '));

  const health = await getJSON(`${base}/health`);
  const q = await postJSON(`${base}/query`, { sql: 'select count(*) as n from orders' });
  const tables = await getJSON(`${base}/datasets/commerce/tables`);
  const progress = await getJSON(`${base}/progress/smoke`, 15_000, auth(offToken));
  report.check('health still works', health.status === 200, `HTTP ${health.status}`);
  report.check('query still works', q.status === 200 && q.json?.status === 'succeeded', `HTTP ${q.status}`);
  report.check('dataset introspection still works', tables.status === 200, `HTTP ${tables.status}`);
  report.check('progress still works', progress.status === 200, `HTTP ${progress.status}`);

  stopGateway(gw.child);
  report.finish();
}

main().catch((err) => {
  console.error(`ai-audit: FAILED — ${err?.message ?? err}`);
  process.exitCode = 1;
});
